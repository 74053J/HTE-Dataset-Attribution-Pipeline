#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""Build a release bundle: code + result tables + documents, never the raw data.

The repository working tree keeps the raw CSVs (they are the objects of study),
but they are not redistributed: every one of them has an upstream source and the
README says so.  This script copies a whitelist into a clean directory so that a
Zenodo / GitHub release cannot pick up the raw files by accident.

Rule of thumb:
  * keep  -- every .py, .bat, .md, .toml, .txt, .yaml/.yml and every table/vector
             artefact produced by the pipeline (.csv outside data/, .npy, .png)
  * drop  -- data/*.csv (raw inputs), data/*.backup*, __pycache__, .pytest_cache,
             anything under results/legacy that is a raw copy, and any file the
             checker below flags as larger than the size cap

Run with --dry-run first: it prints the manifest and the total size without
copying anything.
"""
from __future__ import annotations

import argparse
import hashlib
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent

#: whole subtrees that go in as they are
TREES = ("hte", "scripts", "tests", "docs", "archive")
#: single files that go in
FILES = ("README.md", "README.zh-CN.md", "REPO_STRUCTURE.md", "requirements.txt",
         "fetch_datasets.bat", "run_all.bat", "run_all_except_VirtualLibrary.bat",
         "Single_dataset_full_benchmark.bat",
         "LICENSE", "LICENSE-DATA", "CITATION.cff", ".zenodo.json", ".gitignore",
         "COMPARISON_vs_paper_20261029.md", "verify_checks_parsed.tsv")
#: generated by run_all.bat, never shipped -- except the two inputs bootstrap_ci.py needs
RESULTS_KEEP = ("legacy/grid_all16.csv", "legacy/ceiling_stats_v16.csv")
SHIP_RESULTS = False          # results/ 与 outputs/ 是生成物
SHIP_OUTPUTS = False
#: inside data/, only the mapping tables travel
DATA_KEEP = ("col_mappings.csv", "alias_mapping.yaml")
#: never copied, whatever the glob says
BAN_NAMES = ("__pycache__", ".pytest_cache", ".ipynb_checkpoints")
BAN_SUFFIX = (".pyc", ".pyo", ".log", ".err")
#: anything above this is suspicious for a code/table release
SIZE_CAP_MB = 5.0    # a code/table release is ~0.5 MB; anything above this is a leak


def keep_file(p: Path) -> bool:
    if any(part in BAN_NAMES for part in p.parts):
        return False
    if p.suffix in BAN_SUFFIX:
        return False
    if p.name.startswith("."):
        return False
    return True


def manifest(root: Path = ROOT) -> list[Path]:
    out: list[Path] = []
    for t in TREES:
        base = root / t
        if not base.is_dir():
            continue
        for p in sorted(base.rglob("*")):
            if p.is_file() and keep_file(p):
                out.append(p)
    for f in FILES:
        p = root / f
        if p.is_file():
            out.append(p)
    for name in DATA_KEEP:
        p = root / "data" / name
        if p.is_file():
            out.append(p)
    # results/ and outputs/ hold run_all products (a single acq_idx.npy is ~73 MB), so they
    # are not shipped; only the two legacy inputs bootstrap_ci.py reads travel with the code.
    for rel in RESULTS_KEEP:
        p = root / "results" / rel
        if p.is_file():
            out.append(p)
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dest", default=str(ROOT.parent / "repo_release"))
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--zip", action="store_true",
                    help="also compress the payload into <dest>.zip (what gets uploaded)")
    args = ap.parse_args()

    files = manifest()
    total = sum(p.stat().st_size for p in files)
    big = [p for p in files if p.stat().st_size > SIZE_CAP_MB * 1024 * 1024]
    raw = [p for p in files
           if p.parent.name == "data" and p.suffix == ".csv" and p.name not in DATA_KEEP]

    print("release manifest: %d files, %.1f MB" % (len(files), total / 1048576))
    print("raw data CSVs in the bundle: %d  (expected 0)" % len(raw))
    for p in raw:
        print("   !! %s" % p.relative_to(ROOT))
    if big:
        print("files above the %.0f MB cap:" % SIZE_CAP_MB)
        for p in big:
            print("   %-60s %.1f MB" % (p.relative_to(ROOT), p.stat().st_size / 1048576))
    by_top: dict[str, list[Path]] = {}
    for p in files:
        by_top.setdefault(p.relative_to(ROOT).parts[0], []).append(p)
    for k in sorted(by_top):
        sz = sum(x.stat().st_size for x in by_top[k]) / 1048576
        print("  %-12s %4d files  %6.1f MB" % (k, len(by_top[k]), sz))

    if args.dry_run:
        print("\n(dry run: nothing copied)")
        return 0 if not raw else 1

    dest = Path(args.dest)
    if dest.exists():
        shutil.rmtree(dest)
    dest.mkdir(parents=True)
    for p in files:
        rel = p.relative_to(ROOT)
        target = dest / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(p, target)
    h = hashlib.sha256()
    for p in sorted(dest.rglob("*")):
        if p.is_file():
            h.update(p.relative_to(dest).as_posix().encode())
            h.update(p.read_bytes())
    print("\ncopied to %s" % dest)
    print("manifest sha256: %s" % h.hexdigest())
    if args.zip:
        import zipfile
        zpath = dest.with_suffix(".zip")
        if zpath.exists():
            zpath.unlink()
        with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as zf:
            for p in sorted(dest.rglob("*")):
                if p.is_file():
                    zf.write(p, Path(dest.name) / p.relative_to(dest))
        print("zip: %s (%.1f KB)" % (zpath, zpath.stat().st_size / 1024))
    return 0 if not raw else 1


if __name__ == "__main__":
    sys.exit(main())
