#!/usr/bin/env python
"""Equivalence check (c): hte.grid vs the frozen pipeline and the legacy 16-set grid.

Runs one dataset x all 12 architecture/encoding cells twice:

1. through :mod:`hte.grid` (the new package), and
2. through ``scripts/tables.py:build_grid_all16`` restricted to that one
   dataset.  That function is the reference implementation: it loads the raw CSV
   with the frozen v16 loader, splits/encodes with v16's own functions and fits
   the same 12 cells.  Pointing its ``PIPELINE`` at the repository's frozen
   ``archive/Analysis_all_v16.py`` makes the comparison independent of the
   upstream project checkout.

Both results are then compared with the shipped 16-dataset reference, now kept
at ``results/legacy/grid_all16.csv`` (``fit_seconds`` is excluded: it is
wall-clock time and not reproducible).  The cell values are bit-identical to
``results/grid13_v18.csv`` on this dataset.
"""
from __future__ import annotations

import contextlib
import io
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))

import _common as C

# (alias, stem) -- default is the cheapest paper dataset with a full set of axes
DEFAULT_DATASET = ("AI_RCP_BH", "(AI_RCP_pub)bh_data_clean_all_whitelisted")

NUM_COLS = ["n_rows", "n_features", "r2_train", "r2_test", "rmse_train", "rmse_test"]


def v16_reference(root: Path, alias: str, stem: str) -> pd.DataFrame:
    """Run scripts/tables.py's own 12-cell builder on one dataset."""
    sys.path.insert(0, str(C.SCRIPTS))
    import tables
    tables.PIPELINE = C.LEGACY
    tables.DATA = Path(root)
    tables.DATASET_ORDER = [(alias, stem)]
    tables._PIPE = None                      # do not reuse a cached upstream module
    with contextlib.redirect_stdout(io.StringIO()):
        return tables.build_grid_all16()


def compare(rep: C.Report, label: str, new: pd.DataFrame, ref: pd.DataFrame):
    ok = list(new["model"]) == list(ref["model"]) and \
        list(new["encoding"]) == list(ref["encoding"])
    rep.check("%s: architecture/encoding order (12 cells)" % label, ok,
              note="n=%d" % len(new))
    for col in NUM_COLS:
        d = C.max_abs_diff(new[col].to_numpy(float), ref[col].to_numpy(float))
        rep.check("%s: %s" % (label, col), d <= 1e-12, d)
    rep.equal("%s: status" % label, list(new["status"]), list(ref["status"]))


def main() -> int:
    root = C.data_dir()
    if root is None:
        print("SKIP: data/ directory not found next to this repository")
        return 0

    alias, stem = DEFAULT_DATASET
    if not (Path(root) / (stem + ".csv")).is_file():
        print("SKIP: missing raw file %s" % (Path(root) / (stem + ".csv")))
        return 0

    import hte

    rep = C.Report("test_grid_one_dataset")
    print("[grid] dataset %s (%s)" % (alias, stem))

    print("[grid] running hte.grid ...", flush=True)
    df, raw = hte.load_real_dataset(str(Path(root) / (stem + ".csv")), str(root))
    new = hte.grid.run_dataset(df, alias, raw)

    print("[grid] running the v16/tables.py reference ...", flush=True)
    ref_v16 = v16_reference(root, alias, stem)

    # The reference is the CURRENT published grid, not the retired 16-dataset one:
    # results/legacy/grid_all16.csv predates the metal rule and the slot renames, so
    # comparing against it measured "how much we changed" rather than "is it still
    # the published number".
    #
    # v21: results/ is a GENERATED directory and a v3 checkout ships without it, so a
    # missing reference must skip the CSV comparison, not fail the suite.  The hte-vs-v16
    # comparison above still runs (it needs no stored artefact).
    ref_path = C.RESULTS / "grid13_v18.csv"
    if not ref_path.is_file():
        print("\n[compare] SKIP: %s is absent (results/ is generated by run_all.bat);"
              % ref_path)
        print("          the hte-vs-v16 comparison above is unaffected.")
        out = C.ROOT / "outputs" / "hte_work"
        out.mkdir(parents=True, exist_ok=True)
        new.to_csv(out / ("grid_hte_%s.csv" % alias), index=False, encoding="utf-8")
        return rep.finish()

    ref_csv = pd.read_csv(ref_path)
    ref_csv = ref_csv[ref_csv["dataset"] == alias].reset_index(drop=True)

    print("\n[compare] hte.grid vs v16/tables.py")
    compare(rep, "v16", new, ref_v16)
    print("\n[compare] hte.grid vs results/grid13_v18.csv")
    compare(rep, "csv", new, ref_csv)

    out = C.ROOT / "outputs" / "hte_work"
    out.mkdir(parents=True, exist_ok=True)
    new.to_csv(out / ("grid_hte_%s.csv" % alias), index=False, encoding="utf-8")
    print("\n[wrote] %s" % (out / ("grid_hte_%s.csv" % alias)))
    return rep.finish()


if __name__ == "__main__":
    sys.exit(main())
